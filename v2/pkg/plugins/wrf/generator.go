// generateZodSchemas generates Zod validation schemas
func (g *Generator) generateZodSchemas(types []Type) (*plugins.GeneratedFile, error) {
	var buf bytes.Buffer

	buf.WriteString("// Generated by Wails WRF plugin\n")
	buf.WriteString("// DO NOT EDIT - This file is automatically generated\n\n")
	buf.WriteString("import { z } from 'zod';\n\n")

	for _, typ := range types {
		buf.WriteString(fmt.Sprintf("export const %sSchema = z.object({\n", typ.Name))

		for _, field := range typ.Fields {
			zodType := g.goTypeToZod(field.Type)
			validation := g.extractValidation(field)
			optional := g.isFieldOptional(field)

			fieldName := g.fieldNameToTS(field.Name)

			if optional {
				buf.WriteString(fmt.Sprintf("  %s: %s.optional()%s,\n", fieldName, zodType, validation))
			} else {
				buf.WriteString(fmt.Sprintf("  %s: %s%s,\n", fieldName, zodType, validation))
			}
		}

		buf.WriteString("});\n\n")
		buf.WriteString(fmt.Sprintf("export type %s = z.infer<typeof %sSchema>;\n\n", typ.Name, typ.Name))
	}

	schemaPath := strings.Replace(g.config.Generation.Types.Output, ".ts", "-schemas.ts", 1)
	return &plugins.GeneratedFile{
		Path:      schemaPath,
		Content:   buf.Bytes(),
		Mode:      0644,
		Overwrite: true,
	}, nil
}

// generateEventTypeDefinitions generates event type definitions
func (g *Generator) generateEventTypeDefinitions(services []Service) (*plugins.GeneratedFile, error) {
	var buf bytes.Buffer

	buf.WriteString("// Generated by Wails WRF plugin\n")
	buf.WriteString("// DO NOT EDIT - This file is automatically generated\n\n")

	// Generate event type map
	buf.WriteString("export interface WailsEventMap {\n")

	for _, service := range services {
		for _, method := range service.Methods {
			eventAnn := ExtractEventAnnotation(method.Annotations)
			if eventAnn != nil && eventAnn.EventName != "" {
				eventType := g.formatReturns(method.Results)
				buf.WriteString(fmt.Sprintf("  '%s': %s;\n", eventAnn.EventName, eventType))
			}
		}
	}

	buf.WriteString("}\n\n")

	// Generate typed event functions
	buf.WriteString("import { EventsOn, EventsOff, EventsEmit } from '@wailsjs/runtime/runtime';\n\n")
	buf.WriteString("export function TypedEventsOn<K extends keyof WailsEventMap>(\n")
	buf.WriteString("  eventName: K,\n")
	buf.WriteString("  callback: (data: WailsEventMap[K]) => void\n")
	buf.WriteString("): () => void {\n")
	buf.WriteString("  return EventsOn(eventName as string, callback);\n")
	buf.WriteString("}\n\n")

	buf.WriteString("export function TypedEventsEmit<K extends keyof WailsEventMap>(\n")
	buf.WriteString("  eventName: K,\n")
	buf.WriteString("  data: WailsEventMap[K]\n")
	buf.WriteString("): void {\n")
	buf.WriteString("  EventsEmit(eventName as string, data);\n")
	buf.WriteString("}\n")

	return &plugins.GeneratedFile{
		Path:      g.config.Generation.Events.Output,
		Content:   buf.Bytes(),
		Mode:      0644,
		Overwrite: true,
	}, nil
}

// generateHooksIndex generates index file for hooks
func (g *Generator) generateHooksIndex(services []Service) *plugins.GeneratedFile {
	var buf bytes.Buffer

	buf.WriteString("// Generated by Wails WRF plugin\n")
	buf.WriteString("// DO NOT EDIT - This file is automatically generated\n\n")

	for _, service := range services {
		buf.WriteString(fmt.Sprintf("export * from './%sHooks';\n", service.Name))
	}

	return &plugins.GeneratedFile{
		Path:      fmt.Sprintf("%s/index.ts", g.config.Generation.Hooks.Output),
		Content:   buf.Bytes(),
		Mode:      0644,
		Overwrite: true,
	}
}

